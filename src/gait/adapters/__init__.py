from dataclasses import dataclass
from pathlib import Path

MARKER = "<!-- generated by gait; changes are overwritten by `gait install` -->"


@dataclass(frozen=True)
class FileStatus:
    path: Path
    state: str  # "current", "outdated", "missing" or "foreign"


def file_status(path: Path, expected: str) -> FileStatus:
    if not path.exists():
        return FileStatus(path, "missing")
    current = path.read_text(encoding="utf-8")
    if MARKER not in current:
        return FileStatus(path, "foreign")
    return FileStatus(path, "current" if current == expected else "outdated")


class ForeignFileError(Exception):
    """A file Gait would write already exists and was not generated by Gait."""

    def __init__(self, path: Path):
        super().__init__(str(path))
        self.path = path


def write_files(files: dict[Path, str], force: bool = False) -> list[Path]:
    """Writes generated files, refusing to overwrite files Gait did not create."""
    if not force:
        for path, content in files.items():
            if file_status(path, content).state == "foreign":
                raise ForeignFileError(path)
    written = []
    for path, content in files.items():
        if file_status(path, content).state != "current":
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            written.append(path)
    return written
